export type IconName = keyof typeof PATHS

export function Icon({ name, size = 20, strokeWidth = 1.8, className }: { name: IconName; size?: number; strokeWidth?: number; className?: string }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {PATHS[name]}
    </svg>
  )
}

export function categoryIcon(c: Category, name?: string): IconName {
  if (name && /assinatura|netflix|spotify|prime|youtube|icloud/i.test(name)) return 'repeat'
  switch (c) {
    case 'Moradia':
      return 'home'
    case 'Alimentação':
      return 'cart'
    case 'Transporte':
      return 'car'
    case 'Lazer':
      return 'ticket'
    default:
      return 'wallet'
  }
}
